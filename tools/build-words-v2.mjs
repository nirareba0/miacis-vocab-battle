// data/words_v2.csv → supabase/seed/words_v2.sql
// 単語の段階を CEFR-J（A1〜B2）と NAWL（最難関）で付け直したデータを、words テーブルに入れる（0015 の器を使う）。
// 何度流してもよい: いったん全部を「使わない」にしてから、リストにある語だけを「使う」に戻す。
// 既存の語（NGSL）は id と rank を変えない（対戦・連続チャレンジの履歴と図鑑が word_id で指しているため）。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = path.join(root, 'data', 'words_v2.csv');
const outPath = path.join(root, 'supabase', 'seed', 'words_v2.sql');

function parseLine(line) {
  const out = [];
  let cur = '';
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"') {
      if (q && line[i + 1] === '"') { cur += '"'; i++; } else q = !q;
    } else if (c === ',' && !q) { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur);
  return out;
}

const lines = fs.readFileSync(csvPath, 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter(l => l.trim());
const head = parseLine(lines[0]);
const col = name => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`列 ${name} が無い`);
  return i;
};
const [iKey, iEn, iPos, iLevel, iBand, iStage, iJa, iSrc] = ['sort_key', 'en', 'pos', 'level', 'band', 'stage_range', 'ja', 'source'].map(col);
// 0019: つづりの似た実在の単語・1文字違いのつづりの罠（| 区切り）。無い CSV でも動く
const iLike = head.indexOf('lookalikes');
const iTrap = head.indexOf('misspellings');
const arr = v => `ARRAY[${(v || '').split('|').map(x => x.trim()).filter(Boolean).map(sq).join(', ')}]::text[]`;

const LEVELS = new Set(['A1', 'A2', 'B1', 'B2', 'AC']);
const sq = s => `'${String(s).replace(/'/g, "''")}'`;
const seen = new Set();
const rows = [];
const renames = [];
// 前の版の綴り（小文字・ピリオドなし）。Mr. → mr、July → july
const legacyKey = en => en.toLowerCase().replace(/\./g, '');
for (const line of lines.slice(1)) {
  const c = parseLine(line);
  // 2026-10-03: 固有名・敬称・略語（July・Mr.・TV）は大文字のまま出す。ほかは小文字
  const en = c[iEn].trim();
  const old = legacyKey(en);
  const ja = c[iJa].trim();
  const level = c[iLevel].trim();
  const band = parseInt(c[iBand], 10);
  const stage = parseInt(c[iStage], 10);
  const key = parseInt(c[iKey], 10);
  if (!en || !ja) throw new Error(`訳が空: ${en}`);
  if (!LEVELS.has(level) || !(band >= 1 && band <= 5) || !(stage >= 1 && stage <= 10) || !(key > 0)) throw new Error(`値がおかしい: ${line}`);
  if (!/^[A-Za-z][A-Za-z.'\- ]*$/.test(en)) throw new Error(`つづりがおかしい: ${en}`);
  if (seen.has(old)) throw new Error(`同じ語が2回: ${en}`);
  seen.add(old);
  // 前の版で小文字（july・mr）だった語は、行の id を保ったまま綴りを直す（図鑑と履歴は word_id で指している）
  if (old !== en) renames.push(`update public.words set en = ${sq(en)} where en = ${sq(old)};`);
  rows.push(`  (${100000 + key}, ${sq(en)}, ${sq(ja)}, ${sq(c[iPos].trim())}, ${band}, ${sq(level)}, ${stage}, ${key}, ${sq(c[iSrc].trim() || 'cefrj')}, true, ${arr(iLike >= 0 ? c[iLike] : '')}, ${arr(iTrap >= 0 ? c[iTrap] : '')})`);
}

const sql = `-- Generated by tools/build-words-v2.mjs from data/words_v2.csv
-- Total words: ${rows.length}
-- 出典: CEFR-J Wordlist Version 1.6（東京外国語大学 投野由紀夫研究室）／NAWL 1.2・NGSL 1.2（Browne, Culligan & Phillips, CC BY-SA 4.0）
begin;
${renames.join('\n')}
update public.words set active = false;
insert into public.words (rank, en, ja, pos, band, level, stage_range, sort_key, source, active, lookalikes, misspellings)
values
${rows.join(',\n')}
on conflict (en) do update set
  ja = excluded.ja,
  pos = excluded.pos,
  band = excluded.band,
  level = excluded.level,
  stage_range = excluded.stage_range,
  sort_key = excluded.sort_key,
  source = excluded.source,
  active = true,
  lookalikes = excluded.lookalikes,
  misspellings = excluded.misspellings;
commit;
`;
fs.writeFileSync(outPath, sql);
console.log(`書き出し: ${path.relative(root, outPath)}（${rows.length}語）`);
