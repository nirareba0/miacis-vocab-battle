import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const csvPath = path.join(rootDir, 'data', 'words.csv');
const outDir = path.join(rootDir, 'supabase', 'seed');
const outSqlPath = path.join(outDir, 'words.sql');

if (!fs.existsSync(csvPath)) {
  console.error(`Error: words CSV file not found at ${csvPath}`);
  console.error('Please make sure data/words.csv exists before running this script.');
  process.exit(1);
}

function parseCSVLine(line) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (char === ',' && !inQuotes) {
      result.push(current);
      current = '';
    } else {
      current += char;
    }
  }
  result.push(current);
  return result;
}

const fileContent = fs.readFileSync(csvPath, 'utf8');
const lines = fileContent.split(/\r?\n/).filter(line => line.trim().length > 0);

if (lines.length < 2) {
  console.error('Error: CSV file is empty or missing headers');
  process.exit(1);
}

const headers = parseCSVLine(lines[0]).map(h => h.trim());
const rankIdx = headers.indexOf('rank');
const enIdx = headers.indexOf('en');
const posIdx = headers.indexOf('pos');
const jaIdx = headers.indexOf('ja');
const quizzableIdx = headers.indexOf('quizzable');

if (rankIdx === -1 || enIdx === -1 || jaIdx === -1 || quizzableIdx === -1) {
  console.error('Error: CSV must contain rank, en, pos, ja, quizzable columns');
  process.exit(1);
}

const words = [];
for (let i = 1; i < lines.length; i++) {
  const cols = parseCSVLine(lines[i]);
  const quizzable = cols[quizzableIdx]?.trim();
  if (quizzable === '1') {
    words.push({
      rank: parseInt(cols[rankIdx]?.trim(), 10),
      en: cols[enIdx]?.trim(),
      ja: cols[jaIdx]?.trim(),
      pos: posIdx !== -1 ? cols[posIdx]?.trim() : '',
    });
  }
}

words.sort((a, b) => a.rank - b.rank);

const total = words.length;
if (total === 0) {
  console.error('Error: No quizzable words found');
  process.exit(1);
}

for (let i = 0; i < total; i++) {
  words[i].band = Math.min(5, Math.floor((i * 5) / total) + 1);
}

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

const valuesList = words.map(w => {
  return `(${w.rank}, ${escapeSql(w.en)}, ${escapeSql(w.ja)}, ${escapeSql(w.pos)}, ${w.band})`;
});

const sql = `-- Generated by tools/build-words-seed.mjs
-- Total words: ${total}
INSERT INTO public.words (rank, en, ja, pos, band)
VALUES
  ${valuesList.join(',\n  ')}
ON CONFLICT (rank) DO UPDATE SET
  en = EXCLUDED.en,
  ja = EXCLUDED.ja,
  pos = EXCLUDED.pos,
  band = EXCLUDED.band;
`;

fs.writeFileSync(outSqlPath, sql, 'utf8');
console.log(`Successfully generated ${outSqlPath} with ${total} words.`);
